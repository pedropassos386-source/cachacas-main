            <h3>Concurso Mundial de Bruxelas</h3>

            <p>O Concurso Mundial de Bruxelas é um dos concursos internacionais de destilados mais
                reconhecidos no mundo. Realizado em diferentes países a cada ano, ele reúne um corpo de jurados composto
                por especialistas internacionais — como mestres destiladores, sommeliers, analistas sensoriais e
                críticos de bebidas.

                Todas as avaliações são feitas às cegas, garantindo imparcialidade total.O concurso analisa bebidas como uísques, runs, gins, tequilas, aguardentes e, claro, cachaças,
                considerando critérios como aparência, aroma, sabor, equilíbrio, persistência e tipicidade. As medalhas
                (Ouro, Prata e Grande Ouro) são atribuídas a destilados que atingem faixas específicas de pontuação, o
                que torna a Medalha de Ouro uma chancela de excelência internacional.

                Para a Cachaça Boralina, conquistar uma medalha nesse concurso significa ser reconhecida em padrões
                internacionais, destacando-se entre destilados do mundo todo como um produto de alta qualidade e perfil
                sensorial sofisticado.</p>
        </div>

        <div class="concursos">
            <h3>Concurso de Avaliação da Qualidade das Cachaças de Alambique de Minas Gerais (EMATER-MG)</h3>

            <p>O Concurso de Avaliação da Qualidade das Cachaças de Alambique de Minas Gerais é uma iniciativa da Emater-MG e do Governo do Estado para valorizar a excelência da produção mineira e incentivar a legalização dos alambiques artesanais. Na edição de 2025, as amostras foram submetidas a rigorosas análises laboratoriais físico-químicas e sessões de degustação às cegas por especialistas, que avaliaram aroma, sabor e aspecto visual. A Cachaça Boralina Ouro, envelhecida em bálsamo, consagrou-se como a grande vencedora do certame, conquistando o primeiro lugar geral e o título de melhor cachaça de Minas Gerais entre centenas de produtores participantes.</p>
            <br>

            <p><b>Objetivo:</b> Promover a legalização de alambiques, estimular a melhoria dos processos produtivos e reconhecer a identidade regional da bebida.</p>
            <br>

            <p><b>Avaliação:</b> As amostras passam por análises físico-químicas em laboratórios credenciados e análises sensoriais (degustação às cegas) realizadas por especialistas.</p>
        </div>

        <div class="concursos">
            <h3>Festival da Cachaça de Novo Cruzeiro</h3>

            <p>O Festival da Cachaça de Novo Cruzeiro é o principal evento cultural e econômico do município, consolidando a cidade como a "Capital da Cachaça" no Vale do Jequitinhonha. Realizado anualmente, o evento tem como ponto alto a <b>exposição dos alambiques locais</b>, onde produtores tradicionais apresentam rótulos premiados e cachaças envelhecidas em madeiras nobres, promovendo a degustação e a valorização do saber artesanal.</p>

            <br>

            <p>A celebração vai além da bebida, integrando a <b>gastronomia típica regional</b> e o artesanato local, transformando o Parque de Eventos em um grande centro de convivência. A programação é marcada por <b>shows de artistas nacionais</b>, que atraem milhares de turistas, e pelo tradicional <b>festival de calouros</b>, que valoriza os talentos da terra. Ao unir tradição secular e entretenimento, o festival funciona como uma vitrine essencial para o <b>fortalecimento da economia regional</b> e a preservação da identidade mineira.</p>
